-- ============================================================
--  Visarun: схема базы данных
-- ============================================================
--  Таблицы создаются ЭТИМ скриптом, а не Django-моделями.
--
--  Запуск:
--    psql -U jacob -d vr_project -f db/tables.sql
--
--  Скрипт идемпотентный: при повторном запуске таблицы
--  пересоздаются, данные пропадают. Для заливки данных
--  после него выполните db/import.sql.
--
--  Сквозной ID страны — countries.country_id
--  (числовой код ISO 3166-1 / ОКСМ).
--
--  Индексы не создаются намеренно — по решению проекта.
-- ============================================================

BEGIN;

DROP TABLE IF EXISTS visa_rule       CASCADE;
DROP TABLE IF EXISTS country_group   CASCADE;
DROP TABLE IF EXISTS oksm_groups     CASCADE;
DROP TABLE IF EXISTS oksm            CASCADE;
DROP TABLE IF EXISTS groups          CASCADE;
DROP TABLE IF EXISTS countries       CASCADE;

-- ------------------------------------------------------------
-- Единая таблица стран: merge двух CSV
--   main/data/iso_country.csv                   (249 строк, ISO)
--   main/data/countries_russian_format_oksm.csv  (253 строки, ОКСМ)
-- ------------------------------------------------------------
CREATE TABLE countries (
    country_id               integer      PRIMARY KEY,
    alpha_2                  char(2)      UNIQUE,
    alpha_3                  char(3)      UNIQUE,
    name_en                  varchar(100),
    name_ru                  varchar(100) NOT NULL,
    name_ru_full             varchar(150),
    slug                     varchar(100) UNIQUE,
    iso_3166_2               varchar(20),
    region                   varchar(50),
    region_code              integer,
    sub_region               varchar(50),
    sub_region_code          integer,
    intermediate_region      varchar(50),
    intermediate_region_code integer
);

-- ------------------------------------------------------------
-- Объединения стран: ЕС, СНГ, Шенген, БРИКС, АСЕАН, Лат. Америка
-- ------------------------------------------------------------
CREATE TABLE groups (
    group_id integer      PRIMARY KEY,
    eu_name  varchar(50)  NOT NULL UNIQUE,
    name     varchar(100) NOT NULL
);

-- ------------------------------------------------------------
-- Связь "страна -> объединение" (многие ко многим)
-- country_groups.csv хранит легаси-коды 1..252, в import.sql
-- они пересчитываются в country_id = countries.country_id.
-- ------------------------------------------------------------
CREATE TABLE country_group (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id integer NOT NULL REFERENCES countries(country_id) ON DELETE CASCADE,
    group_id   integer NOT NULL REFERENCES groups(group_id)      ON DELETE CASCADE,
    CONSTRAINT country_group_country_group_uniq UNIQUE (country_id, group_id)
);

-- ------------------------------------------------------------
-- Визовые правила: одна строка на страну.
-- id = country_id из main/data/visa_rule_with_id.csv
-- (скрипт scripts/add_country_id.py). NULL = страна не найдена.
-- visa_status: visa-free / eVisa / eTA / visa required /
--              visa on arrival / ...
-- days: сколько дней можно находиться без визы (NULL = нет)
-- ------------------------------------------------------------
CREATE TABLE visa_rule (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(255) NOT NULL,
    visa_status varchar(50)  NOT NULL,
    days        integer,
    country_id  integer REFERENCES countries(country_id) ON DELETE SET NULL
);

COMMIT;
