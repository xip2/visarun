-- ============================================================
--  Visarun: схема базы данных
-- ============================================================
--  Таблицы создаются ЭТИМ скриптом, а не Django-моделями
--  (в main/models.py у моделей стоит managed = False).
--
--  Запуск:
--    psql -U jacob -d vr_project -f db/tables.sql
--
--  Скрипт идемпотентный: при повторном запуске таблицы
--  пересоздаются, данные пропадают. Для заливки данных
--  после него выполните db/import.sql.
-- ============================================================

BEGIN;

DROP TABLE IF EXISTS visa_rule;
DROP TABLE IF EXISTS country_iso;
DROP TABLE IF EXISTS oksm_groups;
DROP TABLE IF EXISTS oksm;
DROP TABLE IF EXISTS groups;

DROP TABLE IF EXISTS country_visa;
DROP TABLE IF EXISTS visa_type;
DROP TABLE IF EXISTS country_groups;
DROP TABLE IF EXISTS country;

-- ------------------------------------------------------------
-- Объединения стран: ЕС, СНГ, Шенген, БРИКС, АСЕАН, Лат. Америка
-- ------------------------------------------------------------
CREATE TABLE groups (
    code     integer      PRIMARY KEY,
    eu_name  varchar(50)  NOT NULL UNIQUE,
    name     varchar(100) NOT NULL
);

-- ------------------------------------------------------------
-- ОКСМ: справочник стран для таблицы на сайте.
-- code = id из main/data/countries.csv (1..252),
-- name = русское название.
-- ------------------------------------------------------------
CREATE TABLE oksm (
    code integer      PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE,
    slug varchar(100) NOT NULL UNIQUE
);

-- ------------------------------------------------------------
-- Связь "страна -> объединение" (многие ко многим)
-- ------------------------------------------------------------
CREATE TABLE oksm_groups (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id integer NOT NULL REFERENCES oksm(code)   ON DELETE CASCADE,
    group_id   integer NOT NULL REFERENCES groups(code) ON DELETE CASCADE,
    CONSTRAINT oksm_groups_country_group_uniq UNIQUE (country_id, group_id)
);

-- ------------------------------------------------------------
-- Справочник ISO 3166-1 (английские названия, регионы).
-- oksm_code связывает запись с русским названием в oksm;
-- заполняется в db/import.sql по порядку ISO-кодов.
-- ------------------------------------------------------------
CREATE TABLE country_iso (
    name                     varchar(100) NOT NULL,
    alpha_2                  char(2)      NOT NULL,
    alpha_3                  char(3)      NOT NULL,
    country_code             integer      NOT NULL,
    iso_3166_2               varchar(20),
    region                   varchar(50),
    sub_region               varchar(50),
    intermediate_region      varchar(50),
    region_code              integer,
    sub_region_code          integer,
    intermediate_region_code integer,
    oksm_code                integer REFERENCES oksm(code) ON DELETE SET NULL,
    CONSTRAINT country_iso_country_code_uniq UNIQUE (country_code),
    CONSTRAINT country_iso_oksm_code_uniq    UNIQUE (oksm_code)
);

CREATE INDEX country_iso_sub_region_idx ON country_iso (sub_region);

-- ------------------------------------------------------------
-- Визовые правила: одна строка на страну.
-- visa_status: visa-free / eVisa / eTA / visa required /
--              visa on arrival / ...
-- days: сколько дней можно находиться без визы (NULL = нет)
-- oksm_code связывает правило с русским названием в oksm;
-- заполняется в db/import.sql (часть названий в CSV не совпадает
-- с ISO, для них есть таблица синонимов).
-- ------------------------------------------------------------
CREATE TABLE visa_rule (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(255) NOT NULL UNIQUE,
    visa_status varchar(50)  NOT NULL,
    days        integer,
    oksm_code   integer REFERENCES oksm(code) ON DELETE SET NULL
);

CREATE INDEX visa_rule_oksm_code_idx  ON visa_rule (oksm_code);
CREATE INDEX visa_rule_visa_status_idx ON visa_rule (visa_status);

COMMIT;
